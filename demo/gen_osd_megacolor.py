#!/usr/bin/env python3
"""Generate src/main/io/osd_demo_mega.inc from 180x144 4-grey PNGs (demo/megacolor/*.png (all but sprite_*)).

Each picture is quantised to the 2x2 raster's levels by luminance (0 black, 1 dark grey,
2 grey, 3 white) and run-length coded in raster order: one byte per run, (run - 1) << 2 | level,
runs of 1..64. Needs ffmpeg to read the PNGs.

Optional sprite (third argument, default demo/megacolor/sprite_betaflight.png): black / white
pixels on a key colour (pure green, or alpha < 128) = transparent. Packed 2 bits per pixel,
4 per byte, LSB first: 0 transparent, 1 black, 2 white.
"""
import glob, os, subprocess, sys

W, H = 180, 144
src = sys.argv[1] if len(sys.argv) > 1 else 'demo/megacolor'
out = sys.argv[2] if len(sys.argv) > 2 else 'src/main/io/osd_demo_mega.inc'
sprite = sys.argv[3] if len(sys.argv) > 3 else 'demo/megacolor/sprite_betaflight.png'
files = sorted(f for f in glob.glob(os.path.join(src, '*.png')) if not os.path.basename(f).startswith('sprite_'))
if not files:
    sys.exit('no PNGs in ' + src)

def levels(path):
    raw = subprocess.run(['ffmpeg', '-loglevel', 'error', '-i', path, '-vf', f'scale={W}:{H}:flags=neighbor',
                          '-pix_fmt', 'gray', '-f', 'rawvideo', '-'], check=True, capture_output=True).stdout
    assert len(raw) == W * H, path
    greys = sorted(set(raw))
    if len(greys) > 4:  # more than 4 greys: split the 0..255 range evenly
        return [min(3, v * 4 // 256) for v in raw]
    rank = {g: i for i, g in enumerate(greys)}
    if len(greys) < 4:  # fewer: keep black / white at the ends
        rank = {g: min(3, round(g * 3 / 255)) for g in greys}
    return [rank[v] for v in raw]

def sprite_codes(path):
    probe = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', path],
                           check=True, capture_output=True, text=True).stdout.strip().split(',')
    w, h = int(probe[0]), int(probe[1])
    raw = subprocess.run(['ffmpeg', '-loglevel', 'error', '-i', path, '-pix_fmt', 'rgba', '-f', 'rawvideo', '-'],
                         check=True, capture_output=True).stdout
    codes = []
    for i in range(0, w * h * 4, 4):
        r, g, b, a = raw[i:i + 4]
        if a < 128 or (g > 200 and r < 128 and b < 128):
            codes.append(0)
        else:
            codes.append(2 if (r + g + b) > 3 * 128 else 1)
    return w, h, codes

def rle(lv):
    outb, i = [], 0
    while i < len(lv):
        j = i
        while j < len(lv) and lv[j] == lv[i] and j - i < 64:
            j += 1
        outb.append(((j - i - 1) << 2) | lv[i])
        i = j
    return outb

with open(out, 'w') as f:
    f.write(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'license_header.txt')).read() + '\n')
    f.write('/* GENERATED by demo/gen_osd_megacolor.py from %s — do not edit.\n' % src)
    f.write(' * 180x144 pictures, 4 levels, RLE bytes: (run - 1) << 2 | level, raster order. */\n')
    f.write('#define OSD_DEMO_MEGA_PICS %d\n' % len(files))
    names = []
    for n, path in enumerate(files):
        data = rle(levels(path))
        name = 'osdDemoMegaPic%d' % n
        names.append(name)
        f.write('// %s: %d bytes\n' % (os.path.basename(path), len(data)))
        f.write('static const uint8_t %s[%d] = {\n' % (name, len(data)))
        for k in range(0, len(data), 24):
            f.write('    ' + ', '.join('0x%02X' % b for b in data[k:k + 24]) + ',\n')
        f.write('};\n')
        print(path, len(data), 'bytes')
    f.write('static const uint8_t *const osdDemoMegaPics[OSD_DEMO_MEGA_PICS] = { %s };\n' % ', '.join(names))
    if os.path.exists(sprite):
        w, h, codes = sprite_codes(sprite)
        stride = (w + 3) // 4
        data = []
        for y in range(h):
            row = codes[y * w:(y + 1) * w] + [0] * (stride * 4 - w)
            for k in range(0, len(row), 4):
                data.append(row[k] | row[k + 1] << 2 | row[k + 2] << 4 | row[k + 3] << 6)
        f.write('// sprite %s: %dx%d, 2 bpp (0 clear, 1 black, 2 white), 4 px per byte LSB first\n'
                % (os.path.basename(sprite), w, h))
        f.write('#define OSD_DEMO_MEGA_SPRITE_W %d\n#define OSD_DEMO_MEGA_SPRITE_H %d\n' % (w, h))
        f.write('#define OSD_DEMO_MEGA_SPRITE_STRIDE %d\n' % stride)
        f.write('static const uint8_t osdDemoMegaSprite[%d] = {\n' % len(data))
        for k in range(0, len(data), 24):
            f.write('    ' + ', '.join('0x%02X' % b for b in data[k:k + 24]) + ',\n')
        f.write('};\n')
        print(sprite, w, 'x', h, len(data), 'bytes')
