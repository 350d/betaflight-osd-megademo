#!/usr/bin/env python3
"""
Scan demo/music/*.pt3 and regenerate src/main/io/chiptune_tracks.{h,c}.

Track order = filename sort with numeric prefix (01_, 02_, ...).
Display name = filename without leading NNN[_- ] and without .pt3.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PT3_DIR = ROOT / "demo" / "music"
OUT_H = ROOT / "src" / "main" / "io" / "chiptune_tracks.h"
OUT_C = ROOT / "src" / "main" / "io" / "chiptune_tracks.c"


LICENSE = Path(__file__).with_name("license_header.txt").read_text() + "\n"


def sort_key(path: Path):
    m = re.match(r"^(\d+)", path.name)
    if m:
        return (0, int(m.group(1)), path.name.lower())
    return (1, 0, path.name.lower())


def display_name(path: Path) -> str:
    stem = path.stem
    stem = re.sub(r"^\d+[\s_\-]*", "", stem)
    stem = stem.replace("_", " ").strip()
    return stem or path.stem


def c_ident(index: int) -> str:
    return f"track_{index:02d}"


def main() -> int:
    PT3_DIR.mkdir(parents=True, exist_ok=True)
    files = sorted(PT3_DIR.glob("*.pt3"), key=sort_key)
    infos = []
    max_raw = 1
    for i, path in enumerate(files, start=1):
        raw = path.read_bytes()
        if not raw:
            print(f"skip empty: {path.name}", file=sys.stderr)
            continue
        max_raw = max(max_raw, len(raw))
        infos.append(
            {
                "index": i,
                "name": display_name(path),
                "file": path.name,
                "raw_len": len(raw),
                "raw": raw,
                "ident": c_ident(i),
            }
        )
        print(f"{i}: {path.name} -> {len(raw)} bytes")

    count = len(infos)
    OUT_H.write_text(
        LICENSE +
        f"""/*
 * GENERATED by demo/gen_chiptune_tracks.py — do not edit.
 * Source folder: demo/music (numeric prefix sets play order).
 */
#pragma once

#include <stdint.h>

#define CHIPTUNE_TRACK_COUNT {count}
#define CHIPTUNE_TRACK_MAX_RAW {max_raw}

// The module as is, in flash: the player reads it in place (no RAM copy).
typedef struct {{
    const char *name;
    const uint8_t *data;
    uint16_t len;
}} chiptuneTrackInfo_t;

const chiptuneTrackInfo_t *chiptuneGetTrack(uint8_t index1toN);
uint8_t chiptuneTrackCount(void);
"""
    )

    lines = [
        "/*",
        " * GENERATED by demo/gen_chiptune_tracks.py — do not edit.",
        " * Source folder: demo/music",
        " */",
        '#include <stddef.h>',
        '#include "platform.h"',
        "",
        "#ifdef USE_CHIPTUNE",
        "",
        '#include "io/chiptune_tracks.h"',
        "",
    ]

    if not infos:
        lines += [
            "const chiptuneTrackInfo_t *chiptuneGetTrack(uint8_t index1toN)",
            "{",
            "    (void)index1toN;",
            "    return NULL;",
            "}",
            "",
            "uint8_t chiptuneTrackCount(void)",
            "{",
            "    return 0;",
            "}",
            "",
            "#endif /* USE_CHIPTUNE */",
            "",
        ]
    else:
        for info in infos:
            z = info["raw"]
            lines.append(
                f"/* {info['file']} */\n"
                f"static const uint8_t {info['ident']}_pt3[{len(z)}] = {{"
            )
            for off in range(0, len(z), 16):
                chunk = z[off : off + 16]
                lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
            lines.append("};\n")

        lines.append(
            f"static const chiptuneTrackInfo_t chiptuneTracks[CHIPTUNE_TRACK_COUNT] = {{"
        )
        for info in infos:
            name = info["name"].replace("\\", "\\\\").replace('"', '\\"')
            lines.append(
                f'    {{ "{name}", {info["ident"]}_pt3, {info["raw_len"]} }},'
            )
        lines.append("};\n")
        lines += [
            "const chiptuneTrackInfo_t *chiptuneGetTrack(uint8_t index1toN)",
            "{",
            "    if (index1toN < 1 || index1toN > CHIPTUNE_TRACK_COUNT) {",
            "        return NULL;",
            "    }",
            "    return &chiptuneTracks[index1toN - 1];",
            "}",
            "",
            "uint8_t chiptuneTrackCount(void)",
            "{",
            "    return CHIPTUNE_TRACK_COUNT;",
            "}",
            "",
            "#endif /* USE_CHIPTUNE */",
            "",
        ]

    OUT_C.write_text(LICENSE + "\n".join(lines))
    print(f"wrote {OUT_H.relative_to(ROOT)} ({count} tracks, max_raw={max_raw})")
    print(f"wrote {OUT_C.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
